export const searchCities = (query: string): City[] => {
  const q = query.toLowerCase();
  return CITIES.filter(c =>
    c.name.toLowerCase().includes(q) ||
    c.state.toLowerCase().includes(q) ||
    c.tags.some(t => t.includes(q))
  ).slice(0, 8);
};

